public class class_activity_3 {
    public static void main(String[] args) throws Exception {
        int i;

        for (i = 3; i >= 0; --i) {
            System.out.println("* ? ? ?");
        }

        for (i = 1; i <= 3; ++i) {
            System.out.print(i * 1 + " ");
        }

        System.out.println("");

        for (i = 1; i <= 3; ++i) {
            System.out.print(i * 2 + " ");
        }

        System.out.println("");

        for (i = 1; i <= 3; ++i) {
            System.out.print(i * 3 + " ");
        }
    }
}
